export function lang() {
  try {
    return getState()?.settings?.uiLang === "en" ? "en" : "vi";
  } catch {
    return "vi";
  }
}

/** Trả chuỗi theo ngôn ngữ giao diện; thiếu khóa thì trả chính khóa (dễ phát hiện). */
export function t(key, vars) {
  const e = M[key];
  if (!e) return key;
  let s = e[lang() === "en" ? 1 : 0] ?? e[0];
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  return s;
}

export function pickPraise() {
  const list = t("s.praise").split("|");
  return list[Math.floor(Math.random() * list.length)];
}

/** Đặt thuộc tính lang + tiêu đề trang theo ngôn ngữ giao diện. */
export function applyLang() {
  if (typeof document === "undefined") return;
  document.documentElement.lang = lang();
  document.title = `Hán Ngữ Mỗi Ngày · ${t("app.tagline")}`;
}

